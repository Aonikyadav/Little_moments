import type { PhotoCount, PhotoTemplate, Slot } from "./types"

const grid = (count: number, cols: number, gap = 3, margin = 6): Slot[] => {
  const rows = Math.ceil(count / cols)
  const width = (100 - margin * 2 - gap * (cols - 1)) / cols
  const height = (100 - margin * 2 - gap * (rows - 1)) / rows
  return Array.from({ length: count }, (_, index) => ({
    x: Number((margin + (index % cols) * (width + gap)).toFixed(1)),
    y: Number((margin + Math.floor(index / cols) * (height + gap)).toFixed(1)),
    width: Number(width.toFixed(1)),
    height: Number(height.toFixed(1)),
    radius: 1.5,
  }))
}

const strip = (count: number): Slot[] => {
  const marginY = 5
  const totalSlotSpace = 84
  const slotHeight = totalSlotSpace / count
  return Array.from({ length: count }, (_, index) => ({
    x: 8,
    y: Number((marginY + index * slotHeight).toFixed(1)),
    width: 84,
    height: Number((slotHeight * 0.94).toFixed(1)),
    radius: 1.2,
  }))
}

const polaroid = (count = 1): Slot[] => {
  if (count === 1) return [{ x: 8, y: 7, width: 84, height: 72, radius: 1 }]
  return grid(count, 2, 4, 8)
}

const music = (count = 1): Slot[] => {
  if (count === 1) return [{ x: 10, y: 8, width: 80, height: 56, radius: 2 }]
  return [{ x: 8, y: 8, width: 40, height: 56, radius: 2 }, { x: 52, y: 8, width: 40, height: 56, radius: 2 }]
}

const asymmetric = (count: number): Slot[] => {
  if (count === 5) return [
    { x: 7, y: 6, width: 86, height: 42, radius: 2 },
    { x: 7, y: 51, width: 41, height: 21, radius: 2 },
    { x: 52, y: 51, width: 41, height: 21, radius: 2 },
    { x: 7, y: 74, width: 41, height: 20, radius: 2 },
    { x: 52, y: 74, width: 41, height: 20, radius: 2 },
  ]
  if (count === 6) return grid(6, 2, 3, 6)
  return grid(count, Math.ceil(Math.sqrt(count)), 3, 6)
}

